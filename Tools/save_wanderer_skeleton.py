import json
from pathlib import Path
import unreal

project = Path(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir())).resolve()
assert (project / "PrincipledNPR.uproject").is_file(), "Wrong project"
assets = unreal.get_editor_subsystem(unreal.EditorAssetSubsystem)
mesh = assets.load_asset("/Game/NPR/Characters/Wanderer/Meshes/SKM_Wanderer")
assert assets.get_metadata_tag(mesh, "PrincipledNPRWandererImportOwner") == "PrincipledNPR.WandererImport.v1"
skeleton = mesh.get_editor_property("skeleton")
expected = "/Game/NPR/Characters/Wanderer/Meshes/SKM_Wanderer_Skeleton.SKM_Wanderer_Skeleton"
assert skeleton and skeleton.get_path_name() == expected
assert assets.get_metadata_tag(skeleton, "PrincipledNPRWandererImportOwner") in ("", "PrincipledNPR.WandererImport.v1")
assets.set_metadata_tag(skeleton, "PrincipledNPRWandererImportOwner", "PrincipledNPR.WandererImport.v1")
assert assets.save_loaded_asset(skeleton, False)
assert (project / "Content/NPR/Characters/Wanderer/Meshes/SKM_Wanderer_Skeleton.uasset").is_file()
path = project / "Documentation/Assets/Wanderer.UE58.import.json"
record = json.loads(path.read_text(encoding="utf-8"))
record["skeleton_persistence"] = {"asset":expected,"saved_to_canonical_package":True,
    "correction":"Autogenerated skeleton had remained dirty in editor and autosave; explicitly saved its canonical package."}
path.write_text(json.dumps(record,ensure_ascii=False,indent=2),encoding="utf-8")
unreal.log("PNPR_WANDERER_SKELETON_SAVED: " + expected)
